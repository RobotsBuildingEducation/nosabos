const DEFAULT_SUPPORT_LANG = "en";

export function getListenDifferenceCopy(supportLang = DEFAULT_SUPPORT_LANG) {
  const normalized = String(supportLang || "").toLowerCase().trim();
  return LISTEN_DIFFERENCE_I18N[normalized] || LISTEN_DIFFERENCE_I18N.en;
}

export function formatListenDifferenceCopy(template = "", variables = {}) {
  return String(template || "").replace(
    /\{(\w+)\}/g,
    (match, key) => (variables[key] !== undefined ? String(variables[key]) : match),
  );
}
