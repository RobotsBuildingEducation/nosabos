const baseLanguageCode = (value = "") =>
  String(value || "")
    .trim()
    .toLowerCase()
    .split(/[-_]/)[0];

/**
 * A response-final output gate written in the learner's support language.
 * Realtime models are especially prone to copying English-authored control
 * prose when the target language is English, so non-English gates explicitly
 * distinguish exact practice material from forbidden English teacher talk.
 */
export function buildTutorTeacherTalkLanguageGate({
  supportLanguageCode = "",
  targetLanguageCode = "",
} = {}) {
  const support = baseLanguageCode(supportLanguageCode);
  const target = baseLanguageCode(targetLanguageCode);
  const copy = LANGUAGE_GATES[support];
  if (!copy) return "";

  if (support && support === target) {
    return [copy.heading, copy.base, copy.sameLanguage, copy.preflight].join(
      "\n",
    );
  }

  return [
    copy.heading,
    copy.base,
    copy.teacherTalk,
    copy.practice,
    copy.codeSwitch,
    copy.noThird,
    support === "en" ? "" : copy.noEnglishControl,
    copy.preflight,
  ]
    .filter(Boolean)
    .join("\n");
}
