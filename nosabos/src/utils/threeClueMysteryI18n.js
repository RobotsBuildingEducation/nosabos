const DEFAULT_SUPPORT_LANG = "en";

export function getThreeClueMysteryCopy(supportLang = DEFAULT_SUPPORT_LANG) {
  const normalized = String(supportLang || "").toLowerCase().trim();
  return THREE_CLUE_MYSTERY_I18N[normalized] || THREE_CLUE_MYSTERY_I18N.en;
}

export function formatThreeClueMysteryCopy(template = "", variables = {}) {
  return String(template || "").replace(
    /\{(\w+)\}/g,
    (match, key) => (variables[key] !== undefined ? String(variables[key]) : match),
  );
}
