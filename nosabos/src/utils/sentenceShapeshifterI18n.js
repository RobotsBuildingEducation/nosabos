export function getSentenceShapeshifterCopy(language = "en") {
  return (
    SENTENCE_SHAPESHIFTER_COPY[language] || SENTENCE_SHAPESHIFTER_COPY.en
  );
}

export function formatSentenceShapeshifterCopy(template, variables = {}) {
  return String(template || "").replace(/\{(\w+)\}/g, (_, key) =>
    variables[key] == null ? `{${key}}` : String(variables[key]),
  );
}
