export function getDialogueForkCopy(language = "en") {
  return DIALOGUE_FORK_COPY[language] || DIALOGUE_FORK_COPY.en;
}

export function formatDialogueForkCopy(template, variables = {}) {
  return String(template || "").replace(/\{(\w+)\}/g, (_, key) =>
    variables[key] == null ? `{${key}}` : String(variables[key]),
  );
}
