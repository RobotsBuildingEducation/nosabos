const DEFAULT_SUPPORT_LANG = "en";

export function getMorphologyForgeCopy(supportLang = DEFAULT_SUPPORT_LANG) {
  const normalized = String(supportLang || "").toLowerCase().trim();
  return MORPHOLOGY_FORGE_I18N[normalized] || MORPHOLOGY_FORGE_I18N.en;
}

export function formatMorphologyForgeCopy(template = "", variables = {}) {
  return String(template || "").replace(
    /\{(\w+)\}/g,
    (match, key) => (variables[key] !== undefined ? String(variables[key]) : match),
  );
}
