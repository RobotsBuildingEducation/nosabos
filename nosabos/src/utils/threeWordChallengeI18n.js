const DEFAULT_SUPPORT_LANG = "en";

export function getThreeWordChallengeCopy(supportLang = DEFAULT_SUPPORT_LANG) {
  const normalized = String(supportLang || "").toLowerCase().trim();
  return THREE_WORD_CHALLENGE_I18N[normalized] || THREE_WORD_CHALLENGE_I18N.en;
}

export function formatThreeWordChallengeCopy(template = "", variables = {}) {
  return String(template || "").replace(
    /\{(\w+)\}/g,
    (match, key) => (variables[key] !== undefined ? String(variables[key]) : match),
  );
}
