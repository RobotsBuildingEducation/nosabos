export function getWordNeighborhoodsCopy(language = "en") {
  return (
    WORD_NEIGHBORHOODS_COPY[language] || WORD_NEIGHBORHOODS_COPY.en
  );
}

export function formatWordNeighborhoodsCopy(template, variables = {}) {
  return String(template || "").replace(/\{(\w+)\}/g, (_, key) =>
    variables[key] == null ? `{${key}}` : String(variables[key]),
  );
}
