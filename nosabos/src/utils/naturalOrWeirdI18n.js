const DEFAULT_SUPPORT_LANG = "en";

export function getNaturalOrWeirdCopy(supportLang = DEFAULT_SUPPORT_LANG) {
  const normalized = String(supportLang || "").toLowerCase().trim();
  return NATURAL_OR_WEIRD_I18N[normalized] || NATURAL_OR_WEIRD_I18N.en;
}

export function formatNaturalOrWeirdCopy(template = "", variables = {}) {
  return String(template || "").replace(
    /\{(\w+)\}/g,
    (match, key) => (variables[key] !== undefined ? String(variables[key]) : match),
  );
}
